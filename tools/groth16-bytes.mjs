// snarkjs Groth16 objects -> the big-endian byte layout Solana's alt_bn128 syscalls take
// (EIP-197: G1 = x || y, G2 = x.c1 || x.c0 || y.c1 || y.c0). Used by the CU bench and its generator.
export const Q = 21888242871839275222246405745257275088696311157297823662689037894645226208583n;
const be = (v) => Buffer.from(BigInt(v).toString(16).padStart(64, "0"), "hex");
export const g1 = (p) => Buffer.concat([be(p[0]), be(p[1])]);
export const g2 = (p) => Buffer.concat([be(p[0][1]), be(p[0][0]), be(p[1][1]), be(p[1][0])]);
/** Proof bytes for groth16-solana: A is negated so the pairing check equals one. */
export function proofBytes(proof) {
  const a = [proof.pi_a[0], (Q - BigInt(proof.pi_a[1])) % Q];
  return Buffer.concat([g1(a), g2(proof.pi_b), g1(proof.pi_c)]);
}
export const inputBytes = (signals) => Buffer.concat(signals.map(be));

